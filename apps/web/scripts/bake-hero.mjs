import { mkdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = path.join(ROOT, "src", "assets");
const MASTER = path.join(ASSETS, "hero-skyline.jpg");
const WIDTHS = [480, 768, 1080, 1440, 1920];
const LQIP_WIDTH = 32;
const LEGACY = ["hero-skyline-682.avif", "hero-skyline-682.webp"];

const formatBytes = (bytes) => `${(bytes / 1024).toFixed(1)}KB`;

const resize = (width) =>
  sharp(MASTER).resize({
    width,
    withoutEnlargement: true,
  });

await mkdir(ASSETS, { recursive: true });

const writes = WIDTHS.flatMap((width) => {
  const base = path.join(ASSETS, `hero-skyline-${width}`);
  return [
    {
      file: `${base}.avif`,
      run: () => resize(width).avif({ quality: 50 }).toFile(`${base}.avif`),
    },
    {
      file: `${base}.webp`,
      run: () => resize(width).webp({ quality: 78 }).toFile(`${base}.webp`),
    },
    {
      file: `${base}.jpg`,
      run: () =>
        resize(width)
          .jpeg({ mozjpeg: true, progressive: true, quality: 82 })
          .toFile(`${base}.jpg`),
    },
  ];
});

const results = await Promise.all(
  writes.map(async ({ file, run }) => ({ file, info: await run() }))
);

for (const { file, info } of results) {
  console.log(
    `wrote ${path.basename(file)} ${info.width}x${info.height} ${formatBytes(info.size)}`
  );
}

const lqipPath = path.join(ASSETS, "hero-skyline-lqip.webp");
const lqipBuffer = await resize(LQIP_WIDTH)
  .webp({ quality: 20 })
  .toBuffer({ resolveWithObject: true });
await writeFile(lqipPath, lqipBuffer.data);
console.log(
  `wrote ${path.basename(lqipPath)} ${lqipBuffer.info.width}x${lqipBuffer.info.height} ${formatBytes(lqipBuffer.info.size)}`
);

const dataUri = `data:image/webp;base64,${lqipBuffer.data.toString("base64")}`;
const lqipModulePath = path.join(ASSETS, "hero-skyline-lqip.ts");
await writeFile(
  lqipModulePath,
  [
    "// Generated by scripts/bake-hero.mjs — do not edit by hand.",
    `export const heroLqipDataUri = "${dataUri}";`,
    "",
  ].join("\n")
);
console.log(
  `wrote ${path.basename(lqipModulePath)} data URI (${formatBytes(Buffer.byteLength(dataUri))})`
);

await Promise.all(
  LEGACY.map(async (name) => {
    const file = path.join(ASSETS, name);
    try {
      await unlink(file);
      console.log(`removed legacy ${name}`);
    } catch (error) {
      if (
        error &&
        typeof error === "object" &&
        "code" in error &&
        error.code === "ENOENT"
      ) {
        return;
      }
      throw error;
    }
  })
);
